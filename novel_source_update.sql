## 世界观（352字）

塞沃城是一座由Tomcat架构理论建造的服务器城邦。城市的最高权力机构是Engine议会，统领全城运转。Engine之下是多个Host区——每个区对应一个虚拟站点，拥有独立的域名和资源配置。Host区内散布着Context建筑群——每座建筑就是一个Web应用，建筑内部的Wrapper模块是真正处理业务的单元——每个Wrapper对应一个Servlet，没有Main方法，它们无法独立存活，必须依赖Context建筑提供的运行环境。

城市的门户是Connector港——由一组巨大的网络闸门构成，负责接收来自外界的HTTP请求数据包，将其解析为城邦内部可识别的StandardRequest格式，再通过Pipeline管道网络逐层传送到目标Wrapper处理单元。处理结果原路返回。

城邦的生命周期由一套统一的Lifecycle管理系统调度——Init（蓝图审批）、Start（通电运行）、Stop（停机检修）、Destroy（拆除回收）。每个阶段都会触发LifecycleEvent事件广播，Listeners监听器负责执行各阶段的附加操作。

城市的资源调度遵循组合模式——Wrapper是最小的独立单元，Context管理一组Wrapper，Host管理多个Context，Engine统领全部Host。Mapper组件负责根据请求URL中的域名和路径，在城市路由表内精确查找目标Wrapper的位置。塞沃城的运转，依赖Connector与Container两大系统的精密协作。

