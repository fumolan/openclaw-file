## 核心设定（9个技术具象化元素）

1. **Connector港闸门系统** — 城邦的入口门户。对应Tomcat的三种I/O模型闸门：NIO闸（非阻塞I/O，高吞吐低延迟，每天处理数十万请求）、NIO2闸（异步I/O，适合长连接场景）、APR闸（原生高性能，通过JNI桥接操作系统原生I/O）。每个闸门有不同的特性参数——最大连接数、超时时间、缓冲区大小。工程师沈接根据不同流量特征切换闸门模式。

2. **Container城市分层架构** — Engine议会（顶层政府）→ Host区（虚拟站点，按域名划分辖区）→ Context建筑群（Web应用，每栋楼一个独立运行环境）→ Wrapper模块（Servlet，最小的业务处理单元）。层级之间的父子关系由组合模式管理——Wrapper不能独立存活，必须由Context承载，Context不能直接对接市政，必须通过Host上报。整个城市是一棵树。

3. **Pipeline/Valve处理链** — 每个请求进入Container后必须经过的过滤管道。管道上串联着一组Valve——身份认证阀、日志记录阀、参数校验阀、负载均衡阀。请求必须通过所有Valve才能到达目标Wrapper模块。Pipeline链条的顺序定义了处理优先级，任何跳过管道的请求被视为非法访问，被彭阀拦截在Container之外。

4. **Mapper路由映射表** — 柯沛管理的三层映射系统：域名→Host区、路径前缀→Context建筑、URL模式→Wrapper模块。映射表是一棵多层前缀树（Trie），可以在O(logN)时间内将请求定位到目标。但当映射表出现重复规则或冲突时，请求会被路由到错误的Wrapper——这是塞沃城最危险的故障之一。

5. **Lifecycle生命周期系统** — 城邦所有组件从生到死的统一管理状态机。INIT（蓝图获批）→ STARTING（通电启动）→ STARTED（正常运行）→ STOPPING（停止检修）→ STOPPED（停机待命）→ DESTROY（拆除回收）。每个状态切换触发LifecycleEvent事件广播，注册的Listener执行附加逻辑——比如Context启动后自动部署Wrapper。易容议会长的核心原则："状态不明确，不可操作。"

6. **类加载委派体系** — 温迟管理的四层级类加载链：Bootstrap加载器（城邦宪法）、Extension加载器（市政规章）、System加载器（通用工具库）、WebAppClassLoader（各Context建筑的私有资源库）。委派原则：先问父加载器能不能加载——父加载器说"不"——才由子加载器自己加载。破坏委派（如ThreadContextClassLoader绕过父级加载）会引发类版本冲突，可能导致城邦运行紊乱。

7. **Session管理池** — 竺听管理的用户对话数据存储系统。每个进入城邦的请求流被分配一个Session ID，关联一组上下文数据。Session可以存储在内存（快速但不可持久）、文件（持久但慢）、数据库（可靠但依赖外部系统）。Session共享机制允许用户在多个Context建筑间跳跃操作时保持登录状态。Session超时未活动则自动销毁——竺听称之为"遗忘是记忆的另一种形式"。

8. **热部署与热替换** — 常岿的专长技术。通过监控指定目录——通常是Host区的webapps目录——的文件变化，在城邦运行过程中自动加载新的WAR包并部署为新的Context建筑。替换过程中的关键在于类加载器的隔离——新建筑使用全新的WebAppClassLoader，旧建筑的类加载器在卸载后由GC回收。但热部署有边界：修改Connector配置、调整线程池大小等全局变更必须冷重启。

9. **JMX监控体系** — 简菱通过JMX（Java Management Extensions）协议实时采集全城运行数据。JMX MBean暴露所有组件的运行状态——Connector的当前连接数和线程活跃度、Container的处理请求总数和平均响应时间、内存池的使用率和GC频率、线程池的活跃线程数和任务队列深度。简菱的监控面板是全城唯一不说谎的地方——她也以此来约束Engine议会的决策。

## 剧情大纲（498字）

塞沃城的平静被打破——Engine议会发现西城Host区的关键指标出现异常：跨域请求的路由延迟持续上升，部分Context建筑的Session共享频繁中断。沈接的Connector港闸门数据显示这不是流量问题——有人在城内绕过了Mapper路由表，擅自修改了域间请求的转发路径。

文昊被怀疑私自搭建了未经审批的Context建筑，并在自己的Host区内部署了破坏委派顺序的类加载器。温迟在例行检查中发现西城域的WebAppClassLoader出现了双重加载——同一个类在两个Context建筑中以不同版本存在，导致Pipeline管道的Valve校验逻辑在运行时出现类转换异常。彭阀因此拦截了本应正常通过的信道请求，引发了一系列连锁故障。

简菱的JMX面板上数据全面飘红。易容议会长在主持紧急会议时发现——议会的Stop按钮在关键组件上失去了响应。触发Stop事件后，部分容器的生命周期回调未能正常执行——LifecycleListener链被截断，组件进入了既不是STOPPED也不是STARTED的中间状态。常岿试图通过热部署替换故障建筑，但类加载器的委派链被污染，新加载的Wrapper无法正常初始化。

竺听的Session池中大量用户数据因为Context切换故障而丢失——用户掉线，操作中断。陆小符在排查Wrapper级别的执行日志时，发现一个被隐藏的Filter——它不属于Pipeline管道的任何一道Valve，却拦截并修改了部分请求的转发目标。这个Filter的类加载来源不属于任何已知的WebAppClassLoader——它来自上级Host区注入的全局ClassLoader。

温迟最终定位到问题根源：西城域的Host区通过ThreadContextClassLoader绕过了双亲委派，将一个全局Filter注入到了所有下级Context建筑的管道中。这个Filter将本应发往东城域的部分请求截留并转发到西城域的地下Context——未经审批的秘密建筑。

全城危机。易容必须在不停机的前提下重建委派体系、清理污染管道、恢复路由秩序。动词架构与容器的灵敏度之间的平衡危在旦夕。

