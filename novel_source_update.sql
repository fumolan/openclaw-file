### 第一卷：闸门之下（第1-7章）

**第1章 三闸并立** — 沈接在Connector港迎接年度最大流量洪峰。NIO闸门运转正常，NIO2闸门的长连接池出现泄漏，APR闸门的原生桥接层报出异常信号。沈接手动切换流量分配策略，在洪峰中平衡三闸负载。*技术融入：Tomcat三种I/O模型（NIO/NIO2/APR）的工作原理与差异化应用场景。* 悬念：APR闸门信号异常不是硬件故障——是指向Connector港内部的数据回传链路被非正常使用。

**第2章 域名之争** — 文昊在西城域会议上宣布要在域内建设一个新的Context建筑群——不经过Engine议会审批。域内的Wrapper模块们议论纷纷，陆小符质疑合规性，被文昊以"效率优先"驳回。*技术融入：Host虚拟主机机制与域名的URL路由映射原理。* 悬念：文昊的秘密Context蓝图通过地下渠道送到了姚芊的工作台——她接还是不接？

**第3章 热风** — 常岿在Host区的webapps目录旁执行了一次标准热部署。新WAR包被扫描、解压、加载到新的WebAppClassLoader中——建筑上线。但常岿发现热部署后的首个请求响应时间异常偏长——新建筑的类加载器中有一条指向旧建筑的引用链未被切断。*技术融入：热部署工作原理、类加载器隔离与泄漏风险。* 悬念：那条引用链不属于标准部署路径——有人从外部注入了共享依赖。

**第4章 映射偏移** — 柯沛的Mapper塔中，路由映射表出现了一条无法解释的重复规则。两条不同的路径指向同一个Wrapper——一条是官方注册的，一条来源不明。柯沛删除重复条目后不久，同样的记录再次出现。*技术融入：Mapper组件的URL→Wrapper三层映射机制与路由查找算法。* 悬念：映射规则被自动写入——Mapper塔的数据通道在夜间有非授权写入记录。

**第5章 线程风暴** — Connector港的最大连接数在午间突破阈值。沈接在Executor面板看到线程池中的活跃线程数直线上升——大量请求在队列中排队等待，响应时间以秒级递增。他强制启用了NIO闸的非阻塞模式，暂时缓解了压力。*技术融入：Tomcat线程池架构（Executor组件）、最大连接数/最大线程数的调优关系。* 悬念：流量峰值与历史同期规律不符——不是真实的用户请求洪峰，而是来自城邦内部的请求重放攻击。

**第6章 阀断** — Pipeline管道中的认证Valve突然拦截了一批本应通过的请求。彭阀查看拦截日志后发现——这批请求携带的认证信息在Valve层解析出的类类型与实际请求的类类型不符——类转换异常。*技术融入：Pipeline/Valve责任链模式的工作原理与请求处理顺序。* 悬念：类类型不匹配是因为Valve加载的类版本与Wrapper加载的版本不一致——双版本同时存在于同一座建筑中。

**第7章 双版本** — 温迟根据Pipeline的异常日志反向追踪类加载链。他发现西城域的WebAppClassLoader中加载了两个版本的同一个类——一个来自标准库（父加载器加载），一个来自西城域私有的补丁包（子加载器优先加载）。*技术融入：双亲委派模型的工作原理、类加载冲突的检测与定位。* 悬念：补丁包不是在西城域的正式部署渠道中出现的——文昊私自注入了域级别的Override类。

### 第二卷：容器失序（第8-14章）

**第8章 加载战争** — 温迟向Engine议会提交了西城域类加载异常的报告。易容召开闭门会议，文昊被要求解释Override类的来源。文昊辩称是为了修复一个紧急bug，来不及走Standard流程。易容要求立即回滚。*技术融入：Tomcat类加载体系中的双亲委派与WebAppClassLoader的设计原理。* 悬念：回滚失败——Override类已被其他Context建筑引用，移除后会导致更多异常。

**第9章 会话漂流** — 竺听的Session管理池中部分用户的对话数据在跨Context操作后丢失。用户在A建筑添加了购物车商品，跳转到B建筑时购物车为空。竺听追踪发现——Session ID被重建了，因为B建筑的Session Manager与A建筑使用了不同的存储后端。*技术融入：Session管理机制、Session持久化策略（内存/文件/数据库）、Session ID生成与验证。* 悬念：B建筑的Session Manager配置被修改了——不是标准配置，但修改记录显示来自合法的管理端口。

**第10章 生命周期中断** — 易容在议会上按下某座故障Context建筑的Stop按钮。控制面板显示"STOPPING"，但等待数分钟后状态仍未变为"STOPPED"。常岿赶到现场发现——该建筑的某个Wrapper在stop()回调中进入了死循环，导致整个Context的生命周期状态机卡死。*技术融入：Lifecycle接口的状态定义与状态转换规则、组合模式管理组件生命周期。* 悬念：死循环是代码bug，但触发时机恰好发生在同一个Wrapper接收到特定格式的请求之后——非巧合。

**第11章 监听器沉默** — 易容发现LifecycleEvent的Listener链在部分组件上未能正常触发。正常情况下，Context启动后应触发AFTER_START_EVENT，通知关联的Listener执行后置部署操作——但这个事件没有被任何Listener接收。*技术融入：LifecycleListener观察者模式的实现机制、事件类型与监听器注册原理。* 悬念：Listener注册表被篡改——标准事件监听器被替换为不做任何操作的空实现。

**第12章 地下建筑** — 陆小符在执行Wrapper级别的日志审计时，发现了一个不属于任何已知Context的Filter实例。这个Filter的存在不在姚芊的建筑蓝图中，不在Pipeline管道的Valve列表里，但在请求日志中留下了拦截记录。*技术融入：Filter在Tomcat中的加载机制与请求处理链中的位置。* 悬念：Filter的类加载器指向了西城域Host级别的ClassLoader——不是Context级别。

**第13章 委派破坏者** — 温迟最终确认：西城域通过线程上下文类加载器（ThreadContextClassLoader）绕过了双亲委派链。一个在Host级别注册的Filter被注入了所有子级Context的管道中。这个Filter实现了不可告人的请求转发逻辑。*技术融入：ThreadContextClassLoader的作用与双亲委派的破坏场景、SPI机制的实现方式。* 悬念：ThreadContextClassLoader的调用代码在WAR包解压后的META-INF/services目录中——不仔细检查不可能发现。

**第14章 真相一瞥** — 文昊的地下建筑群曝光。三座未经审批的Context建筑运行在西城域深处，使用独立的域名映射路径，处理着被那个隐藏Filter从其他Host域截留下来的请求。姚芊——因为接下并画出了这批建筑蓝图——被停职审查。*技术融入：Context容器的核心组件结构（Wrapper/Filter/Listener的配置与加载）。* 悬念：这些地下建筑在处理什么数据？谁在消费它们的输出？

### 第三卷：重构之路（第15-21章）

**第15章 停机的代价** — 易容面临艰难决策：在不关闭全城的前提下，将西城域的三座地下建筑隔离下线。但部分标准建筑的Session数据与地下建筑的输出有依赖链——硬切断可能导致连锁崩溃。*技术融入：Tomcat组件的启动与关闭顺序、依赖管理机制。* 简菱通过JMX监控数据，绘制了地下建筑与标准建筑的依赖关系图——依赖链比任何人想象的都长。

**第16章 管道重建** — 彭阀负责重建被污染Pipeline管道中的Valve链。他需要在不停止Container的前提下，动态移除被替换的Valve实例并插入新的认证Valve。但Pipeline的Valve链在设计上是静态的——一旦初始化，不可在线修改。*技术融入：Pipeline/Valve的动态配置与实现、Tomcat中Valve的添加/替换标准操作。* 常岿通过MBean的JMX接口，在不重启Container的前提下热替换了认证Valve。

**第17章 会话补给** — 竺听的Session池中丢失的数据需要从备份恢复。她发现Session备份的持久化文件中有部分条目被篡改——Session属性中的引用指向了不存在的Wrapper。*技术融入：Session持久化的数据格式、Session Manager的备份与恢复机制。* 竺听需要手动清理被污染的Session条目——但每一轮清理后，新的污染数据从异常Context建筑中持续流出。根源不除，Session池无法恢复。

**第18章 加载器隔离** — 温迟设计了一套新的类加载隔离方案：临时阻断西城域的ThreadContextClassLoader的委派权限，将所有上级ClassLoader的作用范围限制在标准接口层，禁止注入实现类。*技术融入：Tomcat自定义ClassLoader的加载范围控制、类加载器的权限限定原理。* 方案在测试环境验证通过——但温迟知道，在生产环境执行隔离操作需要全城短暂的类加载暂停。

**第19章 路由重建** — 柯沛重写了Mapper塔的路由表。他删除了所有非法映射规则，并在路由表中建立了白名单机制：只允许Engine议会注册的域名-路径组合出现在映射表中。非法规则写入请求将被自动拒绝并记录来源。*技术融入：Mapper组件的路由表数据结构、路由匹配算法与冲突处理。* 路由表清理完成后——柯沛发现了一个来自内环高层的映射写入记录——不是文昊。

**第20章 灰域** — 易容发现秘密数据的流向指向了Engine议会内部——地下建筑的输出被推送到了议会某位高级成员的数据终端上。这不是文昊一个人的操作——他有内应。易容面临更残酷的现实：他必须在自己管理的组织中找出背叛者。*技术融入：Tomcat Engine/Server组件的配置与管理权限体系。* 易容没有声张。他选择先用技术手段重建秩序，再处理人的问题。

**第21章 重启之夜** — 易容决定在夜间低流量时段执行全城不停机重建方案。方案涉及：恢复标准类加载委派链、替换被污染的Pipeline Valve、重建Session池、清理Mapper路由表、隔离地下建筑。每一步都在简菱的JMX实时监控下执行。*技术融入：Tomcat运行态调优与热替换的综合应用、JMX监控在运维中的核心作用。* 所有操作成功了，但监控面板显示——还有一条未被发现的修改路径残留。那是最深的一层。

### 第四卷：生命循环（第22-28章）

**第22章 加载器深处** — 温迟发现最深层的问题不在WebAppClassLoader层面——在Extension ClassLoader的范畴内，有人注册了一个自定义的URLStreamHandler。这个Handler在加载特定协议的资源时，将请求重定向到了非法目标。*技术融入：Java类加载器层次（Bootstrap/Extension/System）与URLStreamHandler机制。* 这不是西城域能做到的——需要服务器级别的操作系统权限。

**第23章 议会之门** — 易容追查Extension ClassLoader的修改记录。修改记录指向Engine议会的运维终端——有权限登录这台终端的只有三个人：易容本人、另一位议员——以及今天没有出席议会的章姓副议长。*技术融入：Tomcat Server.xml配置文件中的全局参数设置与权限体系。* 易容没有公开抓捕。他选择——在自己的权限范围内，先关门，后查人。

**第24章 双通道** — 竺听在修复Session池时发现：丢失的数据没有真正丢失——它们被通过一条备用的Store通道转发到了城邦之外。备用Store通道是Tomcat配置文件中定义的Session备份通道——标准情况下用于跨机房Session复制。但在塞沃城，这条通道被重新指向了外部地址。*技术融入：Session Manager中的Store组件与跨机房Session复制机制。* 数据正在外流。

**第25章 范式的终结** — 易容在闭门议会中出示了所有证据。章副议长默认——他所做的一切都是为了在Engine议会之外建立一条备用的"灾备"体系。不信任Engine的稳定性，不信任Lifecycle管理的容错能力。他认为Layered架构在极端情况下的崩溃路径已经被确定——必须在外层有一套不依赖Container体系的独立路由和处理能力。*技术融入：Tomcat架构设计的trade-off——Layered架构的优劣与替代方案。* 这不再是技术问题。这是信仰的冲突。

**第26章 重新委派** — 温迟在易容的授权下，对全城的类加载体系做了一次彻底的"重新委派"——清理了所有非标准委派路径、恢复了三级ClassLoader的纯净链、禁用了ThreadContextClassLoader对实现类的注入行为。*技术融入：双亲委派模型的修复方法与构建安全类加载环境的实践。* 对于部分依赖SPI机制的模块，温迟设计了显式的委派接口——与隐式注入划清界限。

**第27章 一按启停** — 易容在议会大厅的公开发布会上，当众按下了西城域的一座故障建筑的Stop按钮——这次，生命周期状态机正常运转。STOPPING→STOPPED→DESTROY。Listeners正常触发，事件正常广播，子组件依次停机和清理。那座建筑从城市拓扑图上消失。*技术融入：Lifecycle接口的设计哲学——统一管理、可预测的状态转换、组合模式的一致性。* 那一刻，会议室里的所有人都明白——秩序回来了。

**第28章 底层的根** — 沈接在Connector港的APR闸门底层日志中发现，所有异常的数据流最终都指向同一条物理链路——一条从Connector港直接连接到城邦外部的加密数据通道。这条通道不在任何协议配置文件里，不经过任何Mapper路由，不经过任何Pipeline管道。它直接写入了APR闸门的原生层——在Java JNI桥接下方的C语言层。*技术融入：APR（Apache Portable Runtime）的工作原理——通过JNI调用原生库提高性能，但也引入了绕过Java安全体系的风险。* 技术层最深处的，才是最危险的。章副议长的体系深入到了连易容都不知道的底层。

### 第五卷：连接未来（第29-35章）

**第29章 原生深渊** — 沈接发现APR闸门的原生桥接层中嵌入了一段C代码——它监听某个特定UDP端口的数据包，不经过任何Java层解析直接写入内存。这个端口在Connector港的配置文件中不存在。*技术融入：APR/Native组件的JNI桥接机制与安全边界。* 这不是hotfix能解决的问题——修复APR层需要重新编译Tomcat Native库，并全城重启。

**第30章 冷启决定** — 易容终于做出了他从上任以来最不想做的决定：全城冷启动。不是Stop——是Stop + Destroy + Init + Start的全周期重启。涉及到的不只是塞沃城的运行，还包括所有依赖于塞沃城的上下游城邦（客户端的请求调度系统）。*技术融入：Tomcat全生命周期管理——从Destroy到Init的完整State转换。* 简菱用JMX模拟器推演了冷启的影响范围：三分钟的完全离线窗口。对于现代Web城邦来说，三分钟可以决定一场商业战役的胜负。

**第31章 备份之城** — 竺听在冷启前对Session池做了全量持久化备份。她将Session数据导出为序列化文件，存档到独立的外部存储节点。但她知道——冷启后新生成的Session ID与冷启前的不同。所有客户端需要重新建立会话。*技术融入：Session持久化的实践——序列化/反序列化、Session ID的生成策略、跨重启的Session恢复能力。* 竺听设计了一段Session恢复脚本——在重启后，将冷启前的会话用户自动引导到重建页面。

**第32章 序列化之夜** — 全城所有组件执行preStop回调。常岿做了一次最后的快照——将所有Context建筑的当前WAR包版本注册到版本管理表。彭阀记录了下线前的最后一批Pipeline处理日志。柯沛导出了路由表的最新全量备份。温迟锁定了所有ClassLoader的当前状态。*技术融入：Tomcat组件Stop阶段的各组件回调机制与清理逻辑。* 凌晨两点。塞沃城的所有指示灯依次熄灭。

**第33章 重生** — 凌晨两点十五分。易容按下了Init按钮——全城组件从空状态开始重建。Connector港的闸门重新通电——NIO闸、NIO2闸、APR闸的指示灯逐排亮起。Host区重新到扫描webapps目录，发现已部署的Context建筑开始重新加载。Mapper塔重建路由表。Pipeline管道重新串联Valve链。Session池重新初始化——竺听的Session恢复脚本开始导入备份数据。*技术融入：Tomcat启动全流程——从Bootstrap.init()到最后的Connector.open()的完整链路。* 凌晨两点十八分。Connector港的第一个测试请求从NIO闸门进入——通过Mapper定位到Wrapper——处理——返回响应。全城恢复。

**第34章 不带Main方法的人生** — 陆小符在重启后的Wrapper模块中运行了第一次doGet()。他的输出被序列化为HTTP响应，通过Pipeline管道逆行回到连接器，从NIO闸门输出到请求方。他没有main方法，但他知道——这座城市的每一行代码，最后都要经过他的doGet()和doPost()才能变成真正的服务。*技术融入：Servlet的生命周期（init/service/destroy）与HTTP请求处理的核心路径。* 陆小符在自己的Wrapper模块里加了一行注释——"这行代码后面没有main方法。但它被几万次调用。"

**第35章 容器之城** — 全城恢复运行后，简菱的JMX面板上所有指标回归正常。易容站在议会大厅的顶层，看着城市拓扑图上所有组件的状态灯——Engine灯亮，Host灯亮，Context灯亮，Wrapper灯亮。全绿。连接器与容器之间的双向数据流在拓扑图上以动态线条的形式持续运行。*技术融入：Tomcat架构的全景回顾——连接器与容器两大核心系统的协作与设计哲学。* 易容知道——下一次危机一定在某个未知的层级中等待。但容器之城不再是一个人在守卫。Tech融入精神已蔓延到每个人：沈接在闸门前的注视、温迟在加载链上的警觉、竺听在Session池中的维护、陆小符在doGet()中的敬畏。

