## 世界观

锁城是一座被巨型数据架构"堆"笼罩的赛博都市。城市的每一层建筑都是一个内存区域——底层是错综复杂的"栈巷"，中间是繁华喧嚣的"堆区"商业带，顶层是冰冷高效的"元数据阁楼"。城市运行着数以百万计的"线程人"——他们是城市的劳动力，在各个区域之间穿梭执行任务。

锁城有一个致命的循环：每隔一段时间，"清扫者"会启动全城肃清——所有线程人被迫停下手中的一切，等待清扫者标记、回收那些失去引用的废弃区域。这个过程被称为"停顿"。每一次停顿，城市的运转都会中断，有人在停顿中死去，有人在停顿中失踪。

锁城的秩序由七大家族维持，他们各自掌控着城市中的关键通道和资源。城市的核心矛盾在于——通道的数量是有限的，而线程人的数量在不断膨胀。当两个线程人同时挤进一条窄巷，谁先进谁后退？当一群人围着一个资源点争夺，谁有资格拿走它？

这些问题的答案，藏在锁城的规则里。而规则，正在崩塌。

